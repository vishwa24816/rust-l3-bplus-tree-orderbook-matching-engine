pub fn gas_cost(opcode: u8) -> u64 {
    match opcode {
        0x00 | 0xf3 | 0xfd | 0xff => 0,
        0x02 | 0x05 | 0x06 | 0x07 => 5,
        0x08 | 0x09 => 8,
        0x0a => 10,
        0x54 => 50,
        0x55 => 5000,
        0x56 | 0x57 => 8,
        0x01 | 0x03 | 0x04 | 0x0b |
        0x10..=0x1d | 0x20 | 0x30..=0x3e |
        0x40..=0x47 | 0x50..=0x53 | 0x5a => 3,
        0x60..=0x7f => 3,
        0x80..=0x8f => 3,
        0x90..=0x9f => 3,
        0xa0..=0xa4 => 3,
        _ => 2,
    }
}
